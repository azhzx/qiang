int main() {
  if ("\a"[0] != 7 || "\e"[0] != 27 || "\v"[0] != 11) return 1;
  if ("\b"[0] != 8 || "\f"[0] != 12) return 2;
  if ("\n"[0] != 10 || "\t"[0] != 9 || "\r"[0] != 13) return 3;
  if ("\101"[0] != 65 || "\x42"[0] != 66) return 4;
  if ("\\"[0] != 92 || "\""[0] != 34) return 5;
  if ("\0x"[0] != 0 || "\0x"[1] != 'x') return 6;
  if ("\x41z"[0] != 'A' || "\x41z"[1] != 'z') return 7;
  if ("\1234"[0] != 83 || "\1234"[1] != '4') return 8;
  return 0;
}
